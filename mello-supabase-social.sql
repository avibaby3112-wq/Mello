create policy "mello_reels_delete_own" on storage.objects for delete to authenticated
using (bucket_id = 'mello-reels' and owner_id = auth.uid()::text);
drop policy if exists "mello_reels_read_authenticated" on storage.objects;
create policy "mello_reels_read_authenticated" on storage.objects for select to authenticated
using (bucket_id = 'mello-reels');
