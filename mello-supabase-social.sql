create or replace function public.mello_profile_counts(target uuid)
returns table(followers bigint, following bigint)
language sql
security definer
set search_path = public
as $$
  select
    (select count(*) from public.follows where following_id = target),
    (select count(*) from public.follows where follower_id = target);
$$;

revoke all on function public.mello_profile_counts(uuid) from public;
grant execute on function public.mello_profile_counts(uuid) to authenticated;

-- Storage bucket for Mello Reels.
insert into storage.buckets (id, name, public) values ('mello-reels','mello-reels',false)
on conflict (id) do nothing;

